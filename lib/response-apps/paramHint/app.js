function extractCommand(text) {
	const stripped = text.replace(/^(!|！|\/|#|＃)/, "").trim().replace(/^秘境攻防/, "灵脉攻防战");
	if (hints[stripped]) return stripped;
	const guildActivityMatch = stripped.match(/^领取宗门(日|周)活奖励$/);
	if (guildActivityMatch) return `领取宗门${guildActivityMatch[1]}活奖励`;
	if (/^(服用|消耗|炼化)$/.test(stripped)) return stripped;
	return null;
}
function App(params) {
	const cmd = extractCommand(params.messageText.trim());
	if (!cmd || !hints[cmd]) return { code: "NO_MATCH" };
	return {
		code: "OK",
		data: { hint: hints[cmd] }
	};
}

