import assert from 'node:assert/strict';
import { after, test } from 'node:test';
import { fileURLToPath } from 'node:url';
import axios from 'axios';
import { Expose, shutdownLogger } from 'alemonjs';
import { createTestApp } from 'alemonjs/testing';
import { goTestFixture } from '../helpers/go-fixture.mjs';
import { gameExpose, GAME_EXPOSE_PROTOCOL } from '../../src/expose';
after(() => shutdownLogger());
const output = goTestFixture(['test', './internal/httpapi', '-run', '^TestRobotBusinessExposeFormationRemove$', '-v', '-count=1'], { cwd: fileURLToPath(new URL('../../../xiuxian-game-server/', import.meta.url)), encoding: 'utf8' }).toString();
const fixture = output.match(/EXPOSE_FORMATION_REMOVE=([^|]+)\|(.+)/);
assert.ok(fixture);
const expiry = fixture[1];
const envelope = JSON.parse(fixture[2]);
test('移除原阵法并保留回执和稳定重试键', async t => {
  const app = createTestApp({ config: { 'qq-bot': { app_id: '123' }, 'xiuxian-game': { backend: { api_url: 'https://offline.invalid', robot_auth_token: 'offline' } } } });
  t.after(() => app.dispose());
  await app.mount({ expose: gameExpose }, undefined, 'xiuxian-game');
  const keys: string[] = [];
  t.mock.method(axios, 'create', () => ({ request: async (request: any) => {
    assert.equal(new URL(request.url).pathname, '/api/v2/robot/business/cave-formations.remove');
    const body = typeof request.data === 'string' ? JSON.parse(request.data) : request.data;
    assert.deepEqual(body.arguments, { keyword: '隐息阵', expected: { key: 'yinxi', expiresAt: expiry } });
    keys.push(request.headers['idempotency-key']);
    return { status: 200, headers: {}, data: JSON.stringify(envelope) };
  } }));
  const event = app.events.privateMessage({ platform: 'qq-bot', userId: 'player' });
  const call = () => app.invoke(event, () => Expose.create().call(GAME_EXPOSE_PROTOCOL, 'xiuxian-game', 'remove_cave_formation', { keyword: '隐息阵', key: 'yinxi', expiresAt: expiry }), 'ai-plugin');
  const run = await call();
  assert.deepEqual(run.errors, []);
  assert.deepEqual(run.messages, []);
  assert.deepEqual(run.actions, []);
  assert.equal(run.value.ok, true, JSON.stringify(run.value));
  if (!run.value.ok) return;
  assert.equal((run.value.data as any).result.removed, true);
  const retry = await call();
  assert.equal(retry.value.ok, true);
  if (retry.value.ok) assert.deepEqual(retry.value.data, run.value.data);
  assert.equal(keys[0], keys[1]);
});
