import assert from 'node:assert/strict';
import { test } from 'node:test';
import axios from 'axios';
import { logger } from 'alemonjs';
import { mockBackendConfig } from './backend-config-helper';
import { registerNotificationRecipient } from '../src/api/bot/notification-relay';
import { startTransportEvent } from '../src/utils/transportTiming';
import { createBackendRequestContext, getEventTransportDiagnosticContext } from '../src/api/bot/context';
import type { GameEvent } from '../src/types/event';

test('recipient registration measures the actual background promise and links the explicit event without leaking identities', async t => {
  mockBackendConfig(t, { api_url: 'https://synthetic.test', worker_token: 'PRIVATE-TOKEN', log_transport_timings: true });
  let now = 100;
  t.mock.method(performance, 'now', () => now);
  const logs: unknown[][] = [];
  t.mock.method(logger, 'info', (...args: unknown[]) => { logs.push(args); });
  let finish!: () => void;
  let calls = 0;
  t.mock.method(axios, 'create', () => ({ post: async (path: string, body: unknown) => {
    calls++;
    assert.equal(path, '/api/v1/internal/notification-relay/recipient');
    assert.equal((body as { uid: string }).uid, 'PRIVATE-PLAYER');
    assert.equal((body as { cid: string }).cid, 'PRIVATE-CHANNEL');
    assert.equal((body as { playerId: number }).playerId, 991234);
    await new Promise<void>(resolve => { finish = resolve; });
    return { data: { data: { accepted: true } } };
  } }));
  const event = { Platform: 'qq-bot', UserId: 'PRIVATE-PLAYER', MessageId: 'PRIVATE-MESSAGE', MessageText: '/商店', name: 'message.create' } as GameEvent;
  startTransportEvent(event);
  now = 120;
  const pending = registerNotificationRecipient('PRIVATE-PLAYER', 'PRIVATE-CHANNEL', 991234, event);
  assert.equal(calls, 1);
  assert.equal(logs.length, 0);
  now = 170;
  finish();
  assert.equal(await pending, undefined);
  const value = logs[0]?.[1] as Record<string, unknown>;
  assert.equal(value.stage, 'notification.recipient');
  assert.equal(value.requestId, createBackendRequestContext(event).requestId);
  assert.equal(value.eventTraceId, getEventTransportDiagnosticContext(event)?.eventTraceId);
  assert.equal(value.commandKey, 'shop.list');
  assert.equal(value.durationMs, 50);
  assert.equal(value.startedFromEventStartMs, 20);
  assert.equal(value.elapsedFromEventStartMs, 70);
  assert.equal(value.outcome, 'fulfilled');
  assert.doesNotMatch(JSON.stringify(logs), /PRIVATE-|991234|accepted/);
});

test('recipient timing preserves registration failures without retry and skips absent targets', async t => {
  mockBackendConfig(t, { api_url: 'https://synthetic.test', worker_token: 'PRIVATE-TOKEN', log_transport_timings: true });
  let calls = 0;
  const failure = new Error('PRIVATE-NETWORK-ERROR');
  const logs: unknown[][] = [];
  t.mock.method(logger, 'info', (...args: unknown[]) => { logs.push(args); });
  t.mock.method(axios, 'create', () => ({ post: async () => { calls++; throw failure; } }));
  await assert.rejects(registerNotificationRecipient('PRIVATE-PLAYER', 'PRIVATE-CHANNEL', 7), error => error === failure);
  assert.equal(calls, 1);
  assert.equal((logs[0]?.[1] as { outcome: string }).outcome, 'rejected');
  assert.doesNotMatch(JSON.stringify(logs), /PRIVATE-/);
  assert.equal(await registerNotificationRecipient(undefined, undefined), undefined);
  assert.equal(calls, 1);
  assert.equal(logs.length, 1);
});
